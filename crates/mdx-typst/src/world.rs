/// The virtual path of the generated main source file.
///
/// The document is compiled from this single file — the writer emits one
/// self-contained source and nothing is `#include`d.
pub const MAIN_PATH: &str = "main.typ";

/// The date [`World::today`] reports when the caller pins none: 2026-01-01.
pub const DEFAULT_TODAY: (i32, u8, u8) = (2026, 1, 1);

/// The virtual path that serves a resolved asset.
///
/// Defined by the writer, which emits the path into the markup; re-exported
/// here because this is the module that serves it.
pub use crate::writer::asset_path;
/// The virtual path that serves the SVG of a rendered diagram.
///
/// Defined by the writer, which emits the path into the markup; re-exported
/// here because this is the module that serves it.
pub use crate::writer::diagram_path;

/// The environment one Typst compilation runs in.
///
/// Built by [`World::new`], which the crate's [`compile`](crate::compile)
/// calls; the type is public so callers can inspect the result
/// ([`line_column`](World::line_column)) or drive Typst themselves.
pub struct World {
    /// The standard library, built once per compilation.
    library: LazyHash<Library>,
    /// Metadata about the fonts in `fonts`, in the same index order.
    book: LazyHash<FontBook>,
    /// The fonts themselves, indexed the same way as `book`.
    fonts: Vec<Font>,
    /// The id of the generated main source.
    main: FileId,
    /// Every source file the world serves, by id.
    sources: HashMap<FileId, Source>,
    /// Every non-source file the world serves (assets and diagram SVGs).
    files: HashMap<FileId, Bytes>,
    /// The fixed date returned by `today`, as `(year, month, day)`.
    today: (i32, u8, u8),
}

impl World {
    /// Builds the world for one compilation of `doc`.
    ///
    /// Generates the Typst source through [`writer::build`], registers every
    /// entry of `assets` and `diagrams` under its virtual path, and loads the
    /// fonts: the bundled [`typst_assets`] fonts first, then the files listed
    /// in [`RenderOptions::fonts`].
    ///
    /// Fails with [`DiagCode::Io`] (`E_IO`) when a listed font file cannot be
    /// read or contains no usable font, and with [`DiagCode::Config`]
    /// (`E_CONFIG`) when [`RenderOptions::deterministic_today`] is not a valid
    /// date.
    pub fn new(
        doc: &Doc,
        assets: &AssetStore,
        math: &MathMap,
        diagrams: &DiagramMap,
        opts: &RenderOptions,
    ) -> Result<Self, Diagnostic> {
        let main = intern(MAIN_PATH).ok_or_else(|| {
            Diagnostic::error(
                DiagCode::Config,
                format!("built-in virtual path {MAIN_PATH:?} is not a usable path"),
            )
        })?;

        let mut fonts = Vec::new();
        for data in typst_assets::fonts() {
            fonts.extend(Font::iter(Bytes::new(data)));
        }
        if !opts.ignore_system_fonts {
            for path in system_cjk_fonts() {
                if let Ok(data) = std::fs::read(&path) {
                    fonts.extend(Font::iter(Bytes::new(data)));
                }
            }
        }
        for path in &opts.fonts {
            let data = std::fs::read(path).map_err(|err| {
                Diagnostic::error(
                    DiagCode::Io,
                    format!("cannot read font file {}: {err}", path.display()),
                )
            })?;
            let known = fonts.len();
            fonts.extend(Font::iter(Bytes::new(data)));
            if fonts.len() == known {
                return Err(Diagnostic::error(
                    DiagCode::Io,
                    format!("font file {} contains no usable font", path.display()),
                ));
            }
        }

        let mut files = HashMap::new();
        for asset in assets.iter() {
            if let Some(id) = intern(&asset_path(asset.id.as_str())) {
                files.insert(id, Bytes::new(asset.bytes.clone()));
            }
        }
        for (path, bytes) in writer::diagram_files(diagrams) {
            if let Some(id) = intern(&path) {
                files.insert(id, Bytes::new(bytes));
            }
        }

        let source = Source::new(main, writer::build(doc, assets, math, diagrams, opts));
        let mut sources = HashMap::new();
        sources.insert(main, source);

        Ok(Self {
            library: LazyHash::new(Library::default()),
            book: LazyHash::new(FontBook::from_fonts(&fonts)),
            fonts,
            main,
            sources,
            files,
            today: parse_today(opts.deterministic_today.as_deref())?,
        })
    }

    /// Locates a compiler diagnostic: maps its span to a 1-based line and
    /// column in the source file the span points into.
    ///
    /// Returns `(None, None)` for detached spans, for spans in files this world
    /// does not serve, and for positions beyond the end of a source.
    pub fn line_column(&self, span: DiagSpan) -> (Option<u32>, Option<u32>) {
        let Some(id) = span.id() else {
            return (None, None);
        };
        let Ok(source) = self.source(id) else {
            return (None, None);
        };
        let Some(offset) = self.range(span).map(|range| range.start) else {
            return (None, None);
        };
        let Some((line, column)) = source.lines().byte_to_line_column(offset) else {
            return (None, None);
        };
        let line = line.try_into().ok().map(|line: u32| line + 1);
        let column = column.try_into().ok().map(|column: u32| column + 1);
        (line, column)
    }

    /// The error reported for a virtual path this world does not serve.
    fn missing(&self, id: FileId) -> FileError {
        FileError::NotFound(PathBuf::from(id.get().vpath().get_with_slash()))
    }
}

impl typst::World for World {
    fn library(&self) -> &LazyHash<Library> {
        &self.library
    }

    fn book(&self) -> &LazyHash<FontBook> {
        &self.book
    }

    fn main(&self) -> FileId {
        self.main
    }

    fn source(&self, id: FileId) -> FileResult<Source> {
        self.sources
            .get(&id)
            .cloned()
            .ok_or_else(|| self.missing(id))
    }

    fn file(&self, id: FileId) -> FileResult<Bytes> {
        if let Some(bytes) = self.files.get(&id) {
            return Ok(bytes.clone());
        }
        if let Some(source) = self.sources.get(&id) {
            return Ok(Bytes::from_string(source.text().to_owned()));
        }
        Err(self.missing(id))
    }

    fn font(&self, index: usize) -> Option<Font> {
        self.fonts.get(index).cloned()
    }

    fn today(&self, _offset: Option<Duration>) -> Option<Datetime> {
        let (year, month, day) = self.today;
        Datetime::from_ymd(year, month, day)
    }
}

/// Interns one project-relative virtual path.
///
/// Returns `None` only for paths that cannot be represented in Typst's virtual
/// file system; the paths this crate builds (`main.typ`, `/assets/…`,
/// `/diagrams/…`) are always representable.
fn intern(path: &str) -> Option<FileId> {
    let vpath = VirtualPath::new(path).ok()?;
    Some(FileId::new(RootedPath::new(VirtualRoot::Project, vpath)))
}

/// CJK-capable font files installed on the host, sorted and bounded.
///
/// Typst embeds its own Latin/math fonts but no CJK face, so a document with
/// Chinese text needs a host font. The scan is deliberately narrow (known CJK
/// families only) and bounded, and `--ignore-system-fonts` turns it off for
/// hermetic, byte-reproducible builds.
fn system_cjk_fonts() -> Vec<PathBuf> {
    const ROOTS: &[&str] = &["/usr/share/fonts", "/usr/local/share/fonts"];
    const MARKERS: &[&str] = &[
        "cjk",
        "sourcehan",
        "source han",
        "wqy",
        "wenquanyi",
        "noto sans sc",
        "noto serif sc",
        "simhei",
        "simsun",
        "pingfang",
        "hiragino",
    ];
    const LIMIT: usize = 6;

    let mut found = Vec::new();
    for root in ROOTS {
        collect_fonts(Path::new(root), 0, &mut found);
    }
    if let Some(home) = std::env::var_os("HOME") {
        for rel in [".local/share/fonts", ".fonts"] {
            collect_fonts(&Path::new(&home).join(rel), 0, &mut found);
        }
    }
    found.retain(|path| {
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default()
            .to_ascii_lowercase();
        let extension = path
            .extension()
            .and_then(|extension| extension.to_str())
            .unwrap_or_default()
            .to_ascii_lowercase();
        matches!(extension.as_str(), "otf" | "ttf" | "ttc" | "otc")
            && MARKERS.iter().any(|marker| name.contains(marker))
    });
    found.sort();
    found.dedup();
    found.truncate(LIMIT);
    found
}

/// Collects font files below `dir`, at most four levels deep.
fn collect_fonts(dir: &Path, depth: usize, out: &mut Vec<PathBuf>) {
    if depth > 4 {
        return;
    }
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        let path = entry.path();
        if file_type.is_dir() {
            collect_fonts(&path, depth + 1, out);
        } else if file_type.is_file() {
            out.push(path);
        }
    }
}

/// The fixed date of `opts`, validated here so that `today` cannot fail.
fn parse_today(value: Option<&str>) -> Result<(i32, u8, u8), Diagnostic> {
    let Some(text) = value else {
        return Ok(DEFAULT_TODAY);
    };
    parse_iso_date(text).ok_or_else(|| {
        Diagnostic::error(
            DiagCode::Config,
            format!("invalid date {text:?}: expected a calendar date in YYYY-MM-DD form"),
        )
    })
}

/// Parses `YYYY-MM-DD`; components are digits only and the date must exist.
fn parse_iso_date(text: &str) -> Option<(i32, u8, u8)> {
    let mut fields = text.split('-');
    let year: i32 = parse_number(fields.next()?, 4)?;
    let month: u8 = parse_number(fields.next()?, 2)?;
    let day: u8 = parse_number(fields.next()?, 2)?;
    if fields.next().is_some() {
        return None;
    }
    // Typst's own calendar check rejects e.g. `2026-02-30`.
    Datetime::from_ymd(year, month, day)?;
    Some((year, month, day))
}

/// Parses an unsigned decimal field of at most `max_digits` digits.
fn parse_number<T: std::str::FromStr>(text: &str, max_digits: usize) -> Option<T> {
    let digits_only = text.bytes().all(|byte| byte.is_ascii_digit());
    if text.is_empty() || text.len() > max_digits || !digits_only {
        return None;
    }
    text.parse().ok()
}

#[cfg(test)]
mod tests {
    use mdx_assets::AssetStore;
    use mdx_core::Doc;
    use typst::World as _;
    use typst::foundations::Datetime;

    use super::{DEFAULT_TODAY, MAIN_PATH, World, intern, parse_today};
    use crate::{DiagramMap, MathMap, PageSetup, RenderOptions, writer};

    #[test]
    fn one_path_interns_to_one_file_id() {
        assert!(intern("main.typ").is_some());
        assert_eq!(intern("main.typ"), intern("main.typ"));
        assert_eq!(
            intern("/assets/img-a1b2c3d4"),
            intern("/assets/img-a1b2c3d4")
        );
    }

    #[test]
    fn today_is_a_fixed_validated_date() {
        assert_eq!(parse_today(None), Ok(DEFAULT_TODAY));
        assert_eq!(parse_today(Some("2026-01-01")), Ok((2026, 1, 1)));
        assert_eq!(parse_today(Some("2026-1-1")), Ok((2026, 1, 1)));
        assert!(parse_today(Some("2026-02-30")).is_err());
        assert!(parse_today(Some("2026-01-01T09:00")).is_err());
        assert!(parse_today(Some("today")).is_err());
        assert!(parse_today(Some("")).is_err());
    }

    #[test]
    fn the_world_serves_the_generated_source_and_a_fixed_date() {
        let doc = Doc::new(Vec::new());
        let assets = AssetStore::new();
        let math = MathMap::new();
        let diagrams = DiagramMap::new();
        let opts = RenderOptions {
            page: PageSetup::default(),
            toc: false,
            pdf_standard: None,
            fonts: Vec::new(),
            ignore_system_fonts: true,
            deterministic_today: None,
            title: None,
        };

        let built = World::new(&doc, &assets, &math, &diagrams, &opts);
        assert!(
            built.is_ok(),
            "world construction failed: {:?}",
            built.as_ref().err()
        );
        let Ok(world) = built else { return };

        // The generated markup is what the world compiles from.
        let generated = writer::build(&doc, &assets, &math, &diagrams, &opts);
        let main = intern(MAIN_PATH);
        assert!(main.is_some());
        assert_eq!(Some(world.main()), main);
        if let Some(id) = main {
            assert!(world.source(id).is_ok());
            if let Ok(served) = world.source(id) {
                assert_eq!(served.text(), generated.as_str());
            }
            assert!(world.file(id).is_ok());
        }

        // The clock is fixed, never the wall clock.
        let fixed = Datetime::from_ymd(DEFAULT_TODAY.0, DEFAULT_TODAY.1, DEFAULT_TODAY.2);
        assert_eq!(world.today(None), fixed);
        assert_eq!(world.today(None), Datetime::from_ymd(2026, 1, 1));

        // Anything that was not registered is reported as missing.
        if let Some(unknown) = intern("/assets/img-000000000000") {
            assert!(matches!(
                world.file(unknown),
                Err(typst::diag::FileError::NotFound(_))
            ));
        }
    }
}
