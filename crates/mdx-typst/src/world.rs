//! The hermetic Typst [`World`] every `mdx` compilation runs in.
//!
//! One [`World`] serves exactly one compilation of one document. It owns the
//! standard library, the font book (the bundled [`typst_assets`] fonts plus the
//! font files the caller lists in [`RenderOptions::fonts`]), an in-memory file
//! system, and a fixed clock.
//!
//! Two properties matter and are enforced here:
//!
//! - **No ambient input.** The only file-system reads are the font files named
//!   in [`RenderOptions::fonts`]; sources, assets and diagrams are passed in
//!   memory. The host's font store is never scanned, so a compile cannot depend
//!   on the machine it runs on.
//! - **A fixed clock.** [`World::today`] always answers with
//!   [`RenderOptions::deterministic_today`], or [`DEFAULT_TODAY`] when the
//!   caller pins no date. The wall clock is never read.
//!
//! # Virtual file system
//!
//! | path | content |
//! |------|---------|
//! | `main.typ` | the source generated by [`writer::build`](crate::writer::build) |
//! | `/assets/<asset id>` | the bytes of one resolved asset ([`asset_path`]) |
//! | `/diagrams/<diagram key>.svg` | the SVG of one rendered diagram ([`diagram_path`]) |
//!
//! The paths are defined by the writer, which is the side that emits them into
//! the markup; this module re-exports the two names [`World::file`] serves, and
//! every asset and diagram of the document is registered under exactly those
//! names. Anything else answers [`FileError::NotFound`].

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use mdx_assets::AssetStore;
use mdx_core::{DiagCode, Diagnostic, Doc};
