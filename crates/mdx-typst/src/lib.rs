//! Typst rendering: the world the compiler runs in, the document writer, and
//! the PDF / SVG-page exports.
//!
//! The pipeline behind `mdx render doc.md -o doc.pdf` is:
//!
//! ```text
//! Doc ──writer::build──► main.typ ──typst::compile──► PagedDocument ──pdf::export──► PDF bytes
//! ```
//!
//! [`compile`] runs the middle step inside a [`world::World`] that serves the
//! generated source, every resolved asset and every rendered diagram from
//! memory, has no access to the host file system beyond the font files named in
//! [`RenderOptions::fonts`], and reports a fixed date instead of the wall clock.
//! The same inputs therefore always produce the same laid-out document, and the
//! exports built on top of it ([`render_pdf`], [`render_svg_pages`]) stay
//! reproducible too.

pub mod page;
pub mod pdf;
pub mod svg;
pub mod world;
pub mod writer;

use std::collections::BTreeMap;
use std::path::PathBuf;

use mdx_assets::AssetStore;
use mdx_core::{Block, DiagCode, Diagnostic, Doc};
use typst::diag::SourceDiagnostic;

use crate::world::World;

/// The laid-out document [`compile`] produces.
///
/// Re-exported so callers of this crate can name the type without depending on
/// `typst-layout` themselves. Typst 0.15 keeps the document type in the
/// `typst-layout` crate: the `typst` facade re-exports `typst-library` only,
/// whose `layout` module carries the layout primitives but no document type, so
/// `typst::layout::PagedDocument` does not resolve.
// API: https://docs.rs/typst-layout/0.15.1/typst_layout/struct.PagedDocument.html
pub use typst_layout::PagedDocument;

/// PDF standards [`RenderOptions::pdf_standard`] accepts.
///
/// Re-exported so a caller (CLI, MCP server, GUI) can request `--pdf-standard
/// a-2b|ua-1` without depending on `typst-pdf` itself.
// API: https://docs.rs/typst-pdf/0.15.1/typst_pdf/enum.PdfStandard.html
pub use typst_pdf::PdfStandard;

/// The paper size of a page set-up.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Paper {
    /// ISO 216 A4, 210 mm × 297 mm.
    A4,
    /// ANSI/ASME Y14.1 Letter, 8.5 in × 11 in.
    Letter,
}

/// Page geometry of the rendered document.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PageSetup {
    /// The paper size.
    pub paper: Paper,
    /// The margin on every side, in millimetres.
    pub margin_mm: f32,
    /// Whether pages carry a page number.
    pub numbered: bool,
}

impl Default for PageSetup {
    /// The page set-up the CLI and MCP renders use by default: A4 with 20 mm
    /// margins and numbered pages.
    fn default() -> Self {
        Self {
            paper: Paper::A4,
            margin_mm: 20.0,
            numbered: true,
        }
    }
}

/// Everything a render needs beyond the document itself.
#[derive(Debug, Clone, PartialEq)]
pub struct RenderOptions {
    /// Page geometry.
    pub page: PageSetup,
    /// Whether the document gets a table of contents.
    pub toc: bool,
    /// The PDF standard to enforce; `None` writes an ordinary PDF.
    pub pdf_standard: Option<PdfStandard>,
    /// Font files that ship with the document or the packager.
    ///
    /// The bundled [`typst_assets`] fonts are always present, so an empty list
    /// still renders; list files here to add or override a family. These are
    /// the only files the renderer reads from the file system; everything else
    /// (source, assets, diagrams) is passed in memory.
    pub fonts: Vec<PathBuf>,
    /// Whether fonts installed on the host may be used.
    ///
    /// `mdx` renders with the bundled [`typst_assets`] fonts plus [`fonts`]
    /// alone and never scans the host's font store, so output stays
    /// reproducible on any machine; this flag records the caller's intent and
    /// does not change the font book.
    ///
    /// [`fonts`]: RenderOptions::fonts
    pub ignore_system_fonts: bool,
    /// The date the document sees as "today", in `YYYY-MM-DD` form.
    ///
    /// `None` means the fixed default date ([`world::DEFAULT_TODAY`]); the wall
    /// clock is never consulted. A malformed date fails with
    /// [`DiagCode::Config`] (`E_CONFIG`).
    pub deterministic_today: Option<String>,
    /// Document title, used for the PDF metadata and the HTML `<title>`.
    pub title: Option<String>,
}

/// LaTeX → Typst expression, one entry per formula in the document.
pub type MathMap = BTreeMap<String, String>;

/// Mermaid source → rendered SVG, one entry per diagram in the document.
pub type DiagramMap = BTreeMap<String, String>;

/// Compiles `doc` into a laid-out Typst document.
///
/// The Typst source is generated by [`writer::build`] and compiled in a
/// [`world::World`] that serves exactly three kinds of virtual file: the
/// generated `main.typ`, the resolved assets under `/assets/<asset id>` and the
/// rendered diagrams under `/diagrams/<diagram key>.svg` (see
/// [`world::asset_path`] and [`world::diagram_path`]).
///
/// Fails with [`DiagCode::Typst`] (`E_TYPST`) when the world cannot be built or
/// Typst rejects the document; the first Typst error is reported with its line
/// and column in the generated source. Typst's warnings are not part of this
/// API's single-diagnostic result.
pub fn compile(
    doc: &Doc,
    assets: &AssetStore,
    math: &MathMap,
    diagrams: &DiagramMap,
    opts: &RenderOptions,
) -> Result<PagedDocument, Diagnostic> {
    // A converted formula can still be invalid Typst (the LaTeX converter is
    // permissive). Rather than failing the whole document on one bad equation,
    // probe the formulas, drop the ones Typst rejects, and let the writer fall
    // back to their raw source. Probing only happens on the failure path.
    let mut math = math.clone();
    loop {
        let world = World::new(doc, assets, &math, diagrams, opts)?;
        match typst::compile::<PagedDocument>(&world).output {
            Ok(document) => return Ok(document),
            Err(errors) => {
                if math.is_empty() {
                    return Err(failure(&world, &errors[..]));
                }
                match first_invalid_math(&math, opts) {
                    Some(key) => {
                        math.remove(&key);
                    }
                    None => return Err(failure(&world, &errors[..])),
                }
            }
        }
    }
}

/// The first [`MathMap`] expression Typst refuses to compile, in key order.
fn first_invalid_math(math: &MathMap, opts: &RenderOptions) -> Option<String> {
    math.iter().find_map(|(key, expr)| {
        let doc = Doc::new(vec![Block::Math {
            latex: key.clone(),
            display: true,
        }]);
        let mut probe = MathMap::new();
        probe.insert(key.clone(), expr.clone());
        let compiles = World::new(&doc, &AssetStore::new(), &probe, &DiagramMap::new(), opts)
            .ok()
            .is_some_and(|world| typst::compile::<PagedDocument>(&world).output.is_ok());
        (!compiles).then(|| key.clone())
    })
}

/// Writes `doc` as PDF bytes — the `mdx render -o doc.pdf` path.
///
/// The PDF standard requested through [`RenderOptions::pdf_standard`] is
/// enforced by [`pdf::export`]; everything else about the layout comes from
/// [`compile`].
pub fn render_pdf(
    doc: &Doc,
    assets: &AssetStore,
    math: &MathMap,
    diagrams: &DiagramMap,
    opts: &RenderOptions,
) -> Result<Vec<u8>, Diagnostic> {
    let document = compile(doc, assets, math, diagrams, opts)?;
    pdf::export(&document, opts)
}

/// Renders `doc` as one standalone SVG per page, in document order — the
/// preview path behind `mdx`'s SVG output.
pub fn render_svg_pages(
    doc: &Doc,
    assets: &AssetStore,
    math: &MathMap,
    diagrams: &DiagramMap,
    opts: &RenderOptions,
) -> Result<Vec<String>, Diagnostic> {
    let document = compile(doc, assets, math, diagrams, opts)?;
    svg::render_pages(&document)
}

/// Folds Typst's compiler diagnostics into the single [`Diagnostic`] this
/// crate's API can return.
///
/// The first error supplies the message, its hints and — when its span points
/// into one of the world's files — a 1-based source position in the generated
/// document; any further errors are summarized as a count so a broken document
/// cannot produce an unbounded message.
fn failure(world: &World, errors: &[SourceDiagnostic]) -> Diagnostic {
    let Some(first) = errors.first() else {
        return Diagnostic::error(DiagCode::Typst, "typst rejected the generated document");
    };

    let mut message = format!("typst rejected the generated document: {}", first.message);
    for hint in &first.hints {
        message.push_str(" (hint: ");
        message.push_str(&hint.v);
        message.push(')');
    }
    if errors.len() > 1 {
        message.push_str(&format!(" (+{} more errors)", errors.len() - 1));
    }

    let diagnostic = Diagnostic::error(DiagCode::Typst, message);
    match world.line_column(first.span) {
        (Some(line), Some(column)) => diagnostic.at(line, column),
        _ => diagnostic,
    }
}
